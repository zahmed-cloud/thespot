"use client";

import { useEffect, useState } from "react";
import {
  TILE_GRADIENTS,
  gradientIndex,
  logoRefFor,
  type PlatformId,
} from "@/lib/logos";

/**
 * The logo tile. Platform mark, verified favicon, or deterministic
 * gradient tile — never a grey globe. Explicit dimensions always, so
 * nothing shifts on load.
 */
export default function LogoTile({
  faviconUrl,
  identityKey,
  title,
  size,
  lazy = false,
}: {
  faviconUrl: string | null;
  identityKey: string;
  title: string;
  size: number;
  lazy?: boolean;
}) {
  const [imgFailed, setImgFailed] = useState(false);
  useEffect(() => setImgFailed(false), [faviconUrl]);

  const ref = logoRefFor(faviconUrl, identityKey, title);
  const style = { width: size, height: size };

  if (ref.kind === "platform") {
    return (
      <span className={`logo-tile mark-${ref.platform}`} style={style} aria-hidden="true">
        <PlatformMark platform={ref.platform} />
      </span>
    );
  }

  if (ref.kind === "img" && !imgFailed) {
    return (
      <span className="logo-tile" style={style} aria-hidden="true">
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={ref.url}
          alt=""
          width={size}
          height={size}
          loading={lazy ? "lazy" : "eager"}
          onError={() => setImgFailed(true)}
        />
      </span>
    );
  }

  const gi = ref.kind === "tile" ? ref.gradient : gradientIndex(identityKey);
  const letter =
    ref.kind === "tile" ? ref.letter : (title.trim()[0] ?? "?").toUpperCase();
  const [from, to] = TILE_GRADIENTS[gi];
  return (
    <span
      className="logo-tile tile-gen"
      style={{
        ...style,
        background: `linear-gradient(160deg, ${from}, ${to})`,
        fontSize: size * 0.44,
      }}
      aria-hidden="true"
    >
      {letter}
    </span>
  );
}

